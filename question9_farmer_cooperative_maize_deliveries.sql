-- (g) DAILY PURCHASE TOTALS AND SCHEDULED JOB [6 MARKS]
CREATE OR REPLACE PROCEDURE pr_refresh_purchases(p_day DATE)
LANGUAGE plpgsql
AS $$
DECLARE
    v_total_weight NUMERIC(14,2);
    v_total_value  NUMERIC(14,2);
BEGIN
    IF p_day IS NULL THEN
        RAISE EXCEPTION 'Purchase date cannot be NULL.';
    END IF;

    SELECT
        COALESCE(SUM(weight_kg), 0.00),
        COALESCE(SUM(total_value), 0.00)
    INTO v_total_weight, v_total_value
    FROM deliveries
    WHERE delivered_on = p_day;

    -- Upsert replaces that date's totals instead of adding them again.
    INSERT INTO daily_purchases
        (purchase_date, total_weight, total_value)
    VALUES
        (p_day, v_total_weight, v_total_value)
    ON CONFLICT (purchase_date)
    DO UPDATE SET
        total_weight = EXCLUDED.total_weight,
        total_value = EXCLUDED.total_value;
END;
$$;

-- Test for a date with deliveries. Repeating this call does not double totals.
CALL pr_refresh_purchases(DATE '2026-11-01');
CALL pr_refresh_purchases(DATE '2026-11-01');

SELECT * FROM daily_purchases
WHERE purchase_date = DATE '2026-11-01';

-- Schedule every day at 01:30 for the PREVIOUS day.
-- Cron fields: minute=30, hour=1, every day.
-- pg_cron must be installed and enabled by the PostgreSQL server administrator.
CREATE EXTENSION IF NOT EXISTS pg_cron;

SELECT cron.schedule(
    'daily-maize-purchase-refresh',
    '30 1 * * *',
    $job$CALL pr_refresh_purchases(CURRENT_DATE - 1);$job$
);

-- Inspect the scheduled job:
SELECT jobid, jobname, schedule, command, active
FROM cron.job
WHERE jobname = 'daily-maize-purchase-refresh';

