-- (b) FUNCTION: CALCULATE NET PAY [6 MARKS]
CREATE OR REPLACE FUNCTION fn_net_pay(p_employee_id INTEGER)
RETURNS NUMERIC(12,2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_basic_salary NUMERIC(12,2);
    v_allowance    NUMERIC(12,2);
    v_deduction    NUMERIC(12,2);
    v_net_pay      NUMERIC(12,2);
BEGIN
    SELECT basic_salary, allowance, deduction
      INTO v_basic_salary, v_allowance, v_deduction
      FROM employees
     WHERE employee_id = p_employee_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Employee ID % does not exist.', p_employee_id;
    END IF;

    v_net_pay := (v_basic_salary + v_allowance) - v_deduction;

    IF v_net_pay < 0 THEN
        RAISE EXCEPTION
            'Net pay for employee % cannot be negative.', p_employee_id;
    END IF;

    RETURN v_net_pay;
END;
$$;

-- (c) PROCEDURE: PROCESS MONTHLY PAYROLL [8 MARKS]
CREATE OR REPLACE PROCEDURE pr_process_payroll(p_month DATE)
LANGUAGE plpgsql
AS $$
DECLARE
    v_month_start DATE;
    v_employee RECORD;
    v_gross_pay NUMERIC(12,2);
    v_net_pay   NUMERIC(12,2);
BEGIN
    IF p_month IS NULL THEN
        RAISE EXCEPTION 'Payroll month cannot be NULL.';
    END IF;

    -- Normalize and require the first day of the month.
    v_month_start := date_trunc('month', p_month)::DATE;

    IF p_month <> v_month_start THEN
        RAISE EXCEPTION
            'Payroll month must be the first day of a month. Received %.',
            p_month;
    END IF;

    -- Process active employees only.
    FOR v_employee IN
        SELECT employee_id, basic_salary, allowance
        FROM employees
        WHERE active = TRUE
        ORDER BY employee_id
    LOOP
        -- Do not change or duplicate an existing employee/month row.
        IF NOT EXISTS (
            SELECT 1
            FROM payroll
            WHERE employee_id = v_employee.employee_id
              AND pay_month = v_month_start
        ) THEN
            v_gross_pay := v_employee.basic_salary + v_employee.allowance;
            v_net_pay := fn_net_pay(v_employee.employee_id);

            INSERT INTO payroll
                (employee_id, pay_month, gross_pay, net_pay)
            VALUES
                (v_employee.employee_id, v_month_start,
                 v_gross_pay, v_net_pay);
        END IF;
    END LOOP;

    RAISE NOTICE 'Payroll processing completed for %.', v_month_start;
END;
$$;

-- (d) TRIGGER: AUDIT ACTUAL BASIC SALARY CHANGES [8 MARKS]
CREATE OR REPLACE FUNCTION trg_log_salary_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.basic_salary IS DISTINCT FROM NEW.basic_salary THEN
        INSERT INTO salary_audit
            (employee_id, old_salary, new_salary, changed_at)
        VALUES
            (OLD.employee_id, OLD.basic_salary, NEW.basic_salary,
             CURRENT_TIMESTAMP);
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_employee_salary_audit
AFTER UPDATE OF basic_salary ON employees
FOR EACH ROW
EXECUTE FUNCTION trg_log_salary_change();

