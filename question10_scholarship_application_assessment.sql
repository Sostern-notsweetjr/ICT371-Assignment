-- (g) ASSESS ALL PENDING APPLICATIONS AND SCHEDULE [6 MARKS]
CREATE OR REPLACE PROCEDURE pr_assess_pending()
LANGUAGE plpgsql
AS $$
DECLARE
    app_record RECORD;
BEGIN
    -- Only PENDING rows are selected. Completed rows are never reassessed.
    FOR app_record IN
        SELECT application_id
        FROM applications
        WHERE status = 'PENDING'
        ORDER BY application_id
    LOOP
        CALL pr_assess_application(app_record.application_id);
    END LOOP;
END;
$$;

-- Test the batch procedure. It processes only applications still PENDING.
CALL pr_assess_pending();

