-- (b) FUNCTION: CHECK WHETHER SERVICE IS DUE [6 MARKS]
CREATE OR REPLACE FUNCTION fn_service_due(p_vehicle_id INTEGER)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_current NUMERIC(12,2);
    v_last_service NUMERIC(12,2);
BEGIN
    SELECT current_odometer, last_service_odometer
      INTO v_current, v_last_service
      FROM vehicles
     WHERE vehicle_id = p_vehicle_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Vehicle ID % does not exist.', p_vehicle_id;
    END IF;

    RETURN (v_current - v_last_service) >= 5000;
END;
$$;

-- (d) TRIGGER FUNCTION: VALIDATE TRIP AND UPDATE ODOMETER [8 MARKS]
CREATE OR REPLACE FUNCTION trg_update_vehicle_odometer()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_current NUMERIC(12,2);
BEGIN
    -- Lock the vehicle row so simultaneous trip inserts cannot use
    -- the same starting odometer value.
    SELECT current_odometer
      INTO v_current
      FROM vehicles
     WHERE vehicle_id = NEW.vehicle_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Vehicle ID % does not exist.', NEW.vehicle_id;
    END IF;

    IF NEW.start_odometer <> v_current THEN
        RAISE EXCEPTION
            'Trip must start at current odometer %. Supplied start: %.',
            v_current, NEW.start_odometer;
    END IF;

    IF NEW.end_odometer <= NEW.start_odometer THEN
        RAISE EXCEPTION
            'End odometer (%) must be greater than start odometer (%).',
            NEW.end_odometer, NEW.start_odometer;
    END IF;

    -- The trigger is the only place that advances current_odometer.
    UPDATE vehicles
       SET current_odometer = NEW.end_odometer
     WHERE vehicle_id = NEW.vehicle_id;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_trip_update_odometer
BEFORE INSERT ON trips
FOR EACH ROW
EXECUTE FUNCTION trg_update_vehicle_odometer();

-- (c) PROCEDURE: RECORD A TRIP [8 MARKS]
-- This procedure inserts the trip only. The trigger updates the odometer.
CREATE OR REPLACE PROCEDURE pr_record_trip(
    p_vehicle_id INTEGER,
    p_trip_on DATE,
    p_start NUMERIC,
    p_end NUMERIC
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_vehicle_id IS NULL OR p_trip_on IS NULL
       OR p_start IS NULL OR p_end IS NULL THEN
        RAISE EXCEPTION
            'Vehicle, trip date, start odometer and end odometer are required.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM vehicles WHERE vehicle_id = p_vehicle_id
    ) THEN
        RAISE EXCEPTION 'Vehicle ID % does not exist.', p_vehicle_id;
    END IF;

    IF p_start < 0 OR p_end <= p_start THEN
        RAISE EXCEPTION
            'Odometer values are invalid: end must be greater than start.';
    END IF;

    INSERT INTO trips
        (vehicle_id, trip_on, start_odometer, end_odometer)
    VALUES
        (p_vehicle_id, p_trip_on, p_start, p_end);

    RAISE NOTICE 'Trip recorded for vehicle %.', p_vehicle_id;
END;
$$;

