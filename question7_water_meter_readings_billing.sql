-- (b) FUNCTION: CALCULATE WATER CHARGE [6 MARKS]
CREATE OR REPLACE FUNCTION fn_water_charge(p_units NUMERIC)
RETURNS NUMERIC(12,2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_charge NUMERIC(12,2);
BEGIN
    IF p_units IS NULL THEN
        RAISE EXCEPTION 'Water consumption cannot be NULL.';
    END IF;

    IF p_units < 0 THEN
        RAISE EXCEPTION 'Water consumption cannot be negative.';
    END IF;

    IF p_units <= 10 THEN
        v_charge := p_units * 5;
    ELSE
        v_charge := (10 * 5) + ((p_units - 10) * 8);
    END IF;

    RETURN ROUND(v_charge, 2);
END;
$$;

-- Function examples:
SELECT fn_water_charge(0)  AS zero_units_charge;       -- K0.00
SELECT fn_water_charge(10) AS ten_units_charge;        -- K50.00
SELECT fn_water_charge(14) AS fourteen_units_charge;   -- K82.00

-- (d) TRIGGER FUNCTION: VALIDATE METER READINGS [8 MARKS]
CREATE OR REPLACE FUNCTION trg_validate_meter_reading()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.current_reading < NEW.previous_reading THEN
        RAISE EXCEPTION
            'Current reading (%) cannot be below previous reading (%).',
            NEW.current_reading, NEW.previous_reading;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reading_must_not_decrease
BEFORE INSERT OR UPDATE ON readings
FOR EACH ROW
EXECUTE FUNCTION trg_validate_meter_reading();

-- (c) PROCEDURE: GENERATE A BILL [8 MARKS]
CREATE OR REPLACE PROCEDURE pr_generate_bill(
    p_reading_id INTEGER,
    p_due_on DATE
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_previous NUMERIC(12,2);
    v_current  NUMERIC(12,2);
    v_units    NUMERIC(12,2);
    v_charge   NUMERIC(12,2);
BEGIN
    IF p_reading_id IS NULL OR p_due_on IS NULL THEN
        RAISE EXCEPTION 'Reading ID and due date are required.';
    END IF;

    SELECT previous_reading, current_reading
      INTO v_previous, v_current
      FROM readings
     WHERE reading_id = p_reading_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reading ID % does not exist.', p_reading_id;
    END IF;

    IF EXISTS (
        SELECT 1 FROM bills WHERE reading_id = p_reading_id
    ) THEN
        RAISE EXCEPTION
            'A bill already exists for reading ID %.', p_reading_id;
    END IF;

    v_units := v_current - v_previous;
    v_charge := fn_water_charge(v_units);

    INSERT INTO bills (reading_id, charge, amount_paid, due_on)
    VALUES (p_reading_id, v_charge, 0.00, p_due_on);

    RAISE NOTICE 'Bill generated for reading %. Consumption: % units; charge: K%.',
        p_reading_id, v_units, v_charge;
END;
$$;

