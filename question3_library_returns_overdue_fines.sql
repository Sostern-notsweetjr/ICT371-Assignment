-- ============================================================
-- ICT371 ADVANCED DATABASE - QUESTION 3
-- LIBRARY RETURNS AND OVERDUE FINES
-- PostgreSQL / PLpgSQL
--
-- Fine rule: K2 for each day AFTER the due date.
-- A return on the due date has no fine.
-- A returned loan stops accumulating fines.
-- ============================================================

-- ------------------------------------------------------------
-- (a) TABLES AND CONSTRAINTS
-- ------------------------------------------------------------

CREATE TABLE books (
    book_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title   VARCHAR(150) NOT NULL
);

CREATE TABLE loans (
    loan_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id       INTEGER NOT NULL REFERENCES books(book_id),
    borrower_name VARCHAR(120) NOT NULL,
    borrowed_on   DATE NOT NULL,
    due_on        DATE NOT NULL,
    returned_on   DATE,
    fine_amount   NUMERIC(12,2) NOT NULL DEFAULT 0
                  CHECK (fine_amount >= 0),
    CONSTRAINT chk_loan_due_date CHECK (due_on >= borrowed_on),
    CONSTRAINT chk_loan_return_date
        CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);

CREATE TABLE loan_audit (
    audit_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id         INTEGER NOT NULL REFERENCES loans(loan_id),
    old_returned_on DATE,
    new_returned_on DATE,
    changed_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE overdue_summary (
    snapshot_date DATE PRIMARY KEY,
    overdue_count INTEGER NOT NULL CHECK (overdue_count >= 0),
    total_fine    NUMERIC(14,2) NOT NULL CHECK (total_fine >= 0)
);

-- ------------------------------------------------------------
-- (b) FUNCTION: calculate the fine for one loan as of a date.
-- The calculation stops at returned_on when the book has
-- already been returned. GREATEST prevents negative fines.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_loan_fine(
    p_loan_id INTEGER,
    p_as_of   DATE
)
RETURNS NUMERIC(12,2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_due_on       DATE;
    v_returned_on  DATE;
    v_effective_on DATE;
    v_overdue_days INTEGER;
BEGIN
    IF p_as_of IS NULL THEN
        RAISE EXCEPTION 'The as-of date cannot be NULL';
    END IF;

    SELECT due_on, returned_on
      INTO v_due_on, v_returned_on
      FROM loans
     WHERE loan_id = p_loan_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Loan ID % does not exist', p_loan_id;
    END IF;

    -- Use the earlier of the requested date and the return date.
    v_effective_on := LEAST(p_as_of, COALESCE(v_returned_on, p_as_of));

    -- A day after due_on is the first day that attracts a fine.
    v_overdue_days := GREATEST(0, v_effective_on - v_due_on);

    RETURN (v_overdue_days * 2)::NUMERIC(12,2);
END;
$$;

-- ------------------------------------------------------------
-- (d) AFTER UPDATE TRIGGER: audit actual changes to returned_on.
-- IS DISTINCT FROM correctly handles NULL-to-date and
-- date-to-NULL comparisons. Unchanged dates are not audited.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_audit_loan_return_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
        INSERT INTO loan_audit
            (loan_id, old_returned_on, new_returned_on, changed_at)
        VALUES
            (NEW.loan_id, OLD.returned_on, NEW.returned_on,
             CURRENT_TIMESTAMP);
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_loan_return_audit
AFTER UPDATE ON loans
FOR EACH ROW
WHEN (OLD.returned_on IS DISTINCT FROM NEW.returned_on)
EXECUTE FUNCTION fn_audit_loan_return_change();

-- ------------------------------------------------------------
-- (c) PROCEDURE: return a loan and store its final fine.
-- The fine is calculated before the update; the update stores
-- returned_on and fine_amount together. The trigger records the
-- return-date change automatically.
-- ------------------------------------------------------------

CREATE OR REPLACE PROCEDURE pr_return_loan(
    p_loan_id     INTEGER,
    p_returned_on DATE
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_borrowed_on DATE;
    v_existing_return DATE;
    v_final_fine NUMERIC(12,2);
BEGIN
    IF p_returned_on IS NULL THEN
        RAISE EXCEPTION 'Return date cannot be NULL';
    END IF;

    SELECT borrowed_on, returned_on
      INTO v_borrowed_on, v_existing_return
      FROM loans
     WHERE loan_id = p_loan_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Loan ID % does not exist', p_loan_id;
    END IF;

    IF v_existing_return IS NOT NULL THEN
        RAISE EXCEPTION 'Loan ID % has already been returned', p_loan_id;
    END IF;

    IF p_returned_on < v_borrowed_on THEN
        RAISE EXCEPTION 'Return date cannot be before the borrowed date';
    END IF;

    v_final_fine := fn_loan_fine(p_loan_id, p_returned_on);

    UPDATE loans
       SET returned_on = p_returned_on,
           fine_amount = v_final_fine
     WHERE loan_id = p_loan_id;
END;
$$;

-- ------------------------------------------------------------
-- (e) VIEW: currently unreturned loans that are overdue today.
-- The fine is calculated as of CURRENT_DATE.
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW v_overdue_loans AS
SELECT
    b.title AS book_title,
    l.borrower_name,
    l.due_on,
    fn_loan_fine(l.loan_id, CURRENT_DATE) AS fine_as_of_today
FROM loans AS l
JOIN books AS b ON b.book_id = l.book_id
WHERE l.returned_on IS NULL
  AND l.due_on < CURRENT_DATE;

-- ------------------------------------------------------------
-- (f) INDEX: support searches for one book's unreturned loans.
-- This is a partial index containing only rows where the book
-- has not been returned.
-- ------------------------------------------------------------

CREATE INDEX idx_loans_unreturned_by_book
    ON loans (book_id, due_on)
    WHERE returned_on IS NULL;

-- Matching query and execution plan:
EXPLAIN
SELECT loan_id, borrower_name, due_on
FROM loans
WHERE book_id = 1
  AND returned_on IS NULL
ORDER BY due_on;

-- ------------------------------------------------------------
-- (g) PROCEDURE: refresh the overdue snapshot for a given date.
-- A loan is counted as unreturned AS OF p_as_of when it has no
-- return date or its return date is later than p_as_of.
-- Only loans already past their due date are overdue.
-- ON CONFLICT replaces the same date's summary on a rerun.
-- ------------------------------------------------------------

CREATE OR REPLACE PROCEDURE pr_refresh_overdue(p_as_of DATE)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_as_of IS NULL THEN
        RAISE EXCEPTION 'Snapshot date cannot be NULL';
    END IF;

    INSERT INTO overdue_summary (snapshot_date, overdue_count, total_fine)
    SELECT
        p_as_of,
        COUNT(*)::INTEGER,
        COALESCE(SUM(fn_loan_fine(loan_id, p_as_of)), 0)
    FROM loans
    WHERE due_on < p_as_of
      AND (returned_on IS NULL OR returned_on > p_as_of)
    ON CONFLICT (snapshot_date)
    DO UPDATE SET
        overdue_count = EXCLUDED.overdue_count,
        total_fine = EXCLUDED.total_fine;
END;
$$;

-- ------------------------------------------------------------
-- SAMPLE DATA: three books and six loans.
-- Dates are relative to CURRENT_DATE so the examples remain
-- useful whenever the script is run.
--
-- Loan 1: open and overdue.
-- Loan 2: returned on its due date (no fine).
-- Loan 3: returned late (fine stops on its return date).
-- Loan 4: open but not yet due.
-- Loan 5: open and overdue.
-- Loan 6: returned on its due date (no fine).
-- ------------------------------------------------------------

INSERT INTO books (title)
VALUES
    ('Database System Concepts'),
    ('Learning PostgreSQL'),
    ('Introduction to Information Systems');

INSERT INTO loans
    (book_id, borrower_name, borrowed_on, due_on, returned_on, fine_amount)
VALUES
    (1, 'Borrower One',   CURRENT_DATE - 20, CURRENT_DATE - 10, NULL, 0),
    (1, 'Borrower Two',   CURRENT_DATE - 12, CURRENT_DATE -  5, NULL, 0),
    (2, 'Borrower Three', CURRENT_DATE - 18, CURRENT_DATE -  8, NULL, 0),
    (2, 'Borrower Four',  CURRENT_DATE -  2, CURRENT_DATE +  5, NULL, 0),
    (3, 'Borrower Five',  CURRENT_DATE - 15, CURRENT_DATE -  7, NULL, 0),
    (3, 'Borrower Six',   CURRENT_DATE -  9, CURRENT_DATE -  2, NULL, 0);

-- Return loans 2 and 6 on their due dates: both should have K0 fine.
CALL pr_return_loan(2, CURRENT_DATE - 5);
CALL pr_return_loan(6, CURRENT_DATE - 2);

-- Return loan 3 late: its fine stops on the return date.
CALL pr_return_loan(3, CURRENT_DATE - 3);

