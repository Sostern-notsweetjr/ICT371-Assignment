-- QUESTION 6: MONTHLY PAYROLL PROCESSING
-- PostgreSQL / PLpgSQL
--
-- Business rules from the practical test:
-- Gross pay = basic salary + allowance.
-- Net pay = gross pay - fixed deduction.
-- Payroll month is stored as the first day of the month.
-- Existing employee/month payroll rows are retained unchanged.
-- The scheduled job requires pg_cron to be installed and enabled.

-- =========================================================
-- CLEAN-UP: allows this script to be rerun
-- =========================================================
DROP VIEW IF EXISTS v_payroll_report CASCADE;
DROP TABLE IF EXISTS salary_audit CASCADE;
DROP TABLE IF EXISTS payroll CASCADE;
DROP TABLE IF EXISTS employees CASCADE;
DROP FUNCTION IF EXISTS fn_net_pay(INTEGER) CASCADE;
DROP PROCEDURE IF EXISTS pr_process_payroll(DATE) CASCADE;
DROP FUNCTION IF EXISTS trg_log_salary_change() CASCADE;

-- (a) DATABASE AND SEED DATA [6 MARKS]
CREATE TABLE employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    basic_salary NUMERIC(12,2) NOT NULL CHECK (basic_salary >= 0),
    allowance NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (allowance >= 0),
    deduction NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (deduction >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE payroll (
    payroll_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(employee_id),
    pay_month DATE NOT NULL CHECK (
        EXTRACT(DAY FROM pay_month) = 1
    ),
    gross_pay NUMERIC(12,2) NOT NULL CHECK (gross_pay >= 0),
    net_pay NUMERIC(12,2) NOT NULL CHECK (net_pay >= 0),
    CONSTRAINT uq_employee_pay_month UNIQUE (employee_id, pay_month)
);

CREATE TABLE salary_audit (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(employee_id),
    old_salary NUMERIC(12,2) NOT NULL,
    new_salary NUMERIC(12,2) NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

