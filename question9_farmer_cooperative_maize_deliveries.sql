-- QUESTION 9: FARMER COOPERATIVE MAIZE DELIVERIES
-- PostgreSQL / PLpgSQL
--
-- Hypothetical maize purchase rates:
-- Grade A = K5 per kilogram
-- Grade B = K4 per kilogram
-- Grade C = K3 per kilogram
--
-- Delivery value is always weight_kg * the rate for its grade.
-- The BEFORE trigger applies the same rule to procedure calls and
-- direct SQL INSERT/UPDATE statements.
-- The scheduled job requires pg_cron to be installed and enabled.

-- =========================================================
-- CLEAN-UP: allows this script to be rerun
-- =========================================================
DROP VIEW IF EXISTS v_farmer_amount_due CASCADE;
DROP TABLE IF EXISTS daily_purchases CASCADE;
DROP TABLE IF EXISTS deliveries CASCADE;
DROP TABLE IF EXISTS farmers CASCADE;
DROP FUNCTION IF EXISTS fn_maize_rate(CHARACTER) CASCADE;
DROP PROCEDURE IF EXISTS pr_receive_delivery(INTEGER, CHARACTER, NUMERIC, DATE) CASCADE;
DROP FUNCTION IF EXISTS trg_calculate_delivery_value() CASCADE;
DROP PROCEDURE IF EXISTS pr_refresh_purchases(DATE) CASCADE;

-- (a) DATABASE AND SEED DATA [6 MARKS]
CREATE TABLE farmers (
    farmer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_number VARCHAR(30) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL
);

CREATE TABLE deliveries (
    delivery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id INTEGER NOT NULL REFERENCES farmers(farmer_id),
    grade CHAR(1) NOT NULL CHECK (grade IN ('A', 'B', 'C')),
    weight_kg NUMERIC(12,2) NOT NULL CHECK (weight_kg > 0),
    unit_rate NUMERIC(10,2) NOT NULL CHECK (unit_rate > 0),
    total_value NUMERIC(14,2) NOT NULL CHECK (total_value > 0),
    delivered_on DATE NOT NULL,
    is_paid BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE daily_purchases (
    purchase_date DATE PRIMARY KEY,
    total_weight NUMERIC(14,2) NOT NULL DEFAULT 0
        CHECK (total_weight >= 0),
    total_value NUMERIC(14,2) NOT NULL DEFAULT 0
        CHECK (total_value >= 0)
);

