ORDER BY loan_id;

-- 3. Check the audit trail.
-- It should contain one row for each actual return-date change.
SELECT * FROM loan_audit ORDER BY audit_id;

-- 4. Display currently overdue and unreturned loans.
SELECT * FROM v_overdue_loans ORDER BY due_on;

-- 5. Refresh today's overdue summary and inspect it.
CALL pr_refresh_overdue(CURRENT_DATE);
SELECT * FROM overdue_summary ORDER BY snapshot_date;

-- 6. Run the refresh again to demonstrate replacement, not duplication.
CALL pr_refresh_overdue(CURRENT_DATE);
SELECT * FROM overdue_summary ORDER BY snapshot_date;

