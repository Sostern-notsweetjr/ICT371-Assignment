-- (b) FUNCTION: FREE BEDS [6]
CREATE OR REPLACE FUNCTION fn_free_beds(p_room_id INTEGER)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_capacity INTEGER;
    v_occupied INTEGER;
BEGIN
    SELECT capacity INTO v_capacity
    FROM rooms WHERE room_id = p_room_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Room ID % does not exist.', p_room_id;
    END IF;

    SELECT COUNT(*)::INTEGER INTO v_occupied
    FROM allocations
    WHERE room_id = p_room_id AND status = 'ACTIVE';

    RETURN v_capacity - v_occupied;
END;
$$;

-- (d) TRIGGER FUNCTION: CAPACITY AND ONE ACTIVE ALLOCATION [8]
CREATE OR REPLACE FUNCTION trg_check_allocation_capacity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_capacity INTEGER;
    v_occupied INTEGER;
    v_student_active INTEGER;
BEGIN
    IF NEW.status = 'ACTIVE' THEN
        -- Lock room row to serialize simultaneous allocations to this room.
        SELECT capacity INTO v_capacity
        FROM rooms WHERE room_id = NEW.room_id FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Room ID % does not exist.', NEW.room_id;
        END IF;

        SELECT COUNT(*)::INTEGER INTO v_occupied
        FROM allocations a
        WHERE a.room_id = NEW.room_id
          AND a.status = 'ACTIVE'
          AND (TG_OP = 'INSERT' OR a.allocation_id <> NEW.allocation_id);

        IF v_occupied >= v_capacity THEN
            RAISE EXCEPTION 'Room % is full. Capacity is %.',
                NEW.room_id, v_capacity;
        END IF;

        SELECT COUNT(*)::INTEGER INTO v_student_active
        FROM allocations a
        WHERE a.student_id = NEW.student_id
          AND a.status = 'ACTIVE'
          AND (TG_OP = 'INSERT' OR a.allocation_id <> NEW.allocation_id);

        IF v_student_active > 0 THEN
            RAISE EXCEPTION
                'Student % already has an ACTIVE allocation.', NEW.student_id;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_allocation_capacity
BEFORE INSERT OR UPDATE ON allocations
FOR EACH ROW
EXECUTE FUNCTION trg_check_allocation_capacity();

-- (c) PROCEDURE: ALLOCATE A ROOM [8]
CREATE OR REPLACE PROCEDURE pr_allocate_room(
    p_student_id INTEGER,
    p_room_id INTEGER,
    p_allocated_on DATE
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_capacity INTEGER;
    v_occupied INTEGER;
BEGIN
    IF p_student_id IS NULL OR p_room_id IS NULL OR p_allocated_on IS NULL THEN
        RAISE EXCEPTION 'Student, room and allocation date are required.';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM students WHERE student_id = p_student_id) THEN
        RAISE EXCEPTION 'Student ID % does not exist.', p_student_id;
    END IF;

    SELECT capacity INTO v_capacity
    FROM rooms WHERE room_id = p_room_id FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Room ID % does not exist.', p_room_id;
    END IF;

    IF EXISTS (
        SELECT 1 FROM allocations
        WHERE student_id = p_student_id AND status = 'ACTIVE'
    ) THEN
        RAISE EXCEPTION
            'Student % already has an ACTIVE allocation.', p_student_id;
    END IF;

    SELECT COUNT(*)::INTEGER INTO v_occupied
    FROM allocations
    WHERE room_id = p_room_id AND status = 'ACTIVE';

    IF v_occupied >= v_capacity THEN
        RAISE EXCEPTION 'Room % has no free beds.', p_room_id;
    END IF;

    INSERT INTO allocations
        (student_id, room_id, allocated_on, released_on, status)
    VALUES
        (p_student_id, p_room_id, p_allocated_on, NULL, 'ACTIVE');

    RAISE NOTICE 'Student % allocated to room %.',
        p_student_id, p_room_id;
END;
$$;

