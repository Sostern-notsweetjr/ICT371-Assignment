-- (g) DAILY OCCUPANCY SUMMARY AND JOB [6]
CREATE TABLE occupancy_snapshot (
    snapshot_date DATE NOT NULL,
    room_id INTEGER NOT NULL REFERENCES rooms(room_id),
    occupied_beds INTEGER NOT NULL CHECK (occupied_beds >= 0),
    free_beds INTEGER NOT NULL CHECK (free_beds >= 0),
    PRIMARY KEY (snapshot_date, room_id)
);

CREATE OR REPLACE PROCEDURE pr_refresh_occupancy()
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO occupancy_snapshot
        (snapshot_date, room_id, occupied_beds, free_beds)
    SELECT CURRENT_DATE, room_id, occupied_beds, free_beds
    FROM v_room_occupancy
    ON CONFLICT (snapshot_date, room_id)
    DO UPDATE SET
        occupied_beds = EXCLUDED.occupied_beds,
        free_beds = EXCLUDED.free_beds;
END;
$$;

-- Test; reruns update the same date/room rows.
CALL pr_refresh_occupancy();

SELECT * FROM occupancy_snapshot
WHERE snapshot_date = CURRENT_DATE
ORDER BY room_id;

-- Schedule daily at 23:55. Requires pg_cron installed and configured
-- by the PostgreSQL server administrator.
CREATE EXTENSION IF NOT EXISTS pg_cron;

SELECT cron.schedule(
    'refresh-hostel-occupancy-daily',
    '55 23 * * *',
    'CALL pr_refresh_occupancy();'
