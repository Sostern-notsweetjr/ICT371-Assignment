-- Demonstrate rerunning a month: existing rows stay unchanged.
CALL pr_process_payroll(DATE '2026-10-01');

-- Check that rows are not duplicated.
SELECT pay_month, COUNT(*) AS payroll_rows
FROM payroll
GROUP BY pay_month
ORDER BY pay_month;

-- Schedule the procedure for 02:00 on the first day of every month.
-- At run time, the expression passes the first day of the PREVIOUS month.
-- Requires pg_cron installed and enabled by the PostgreSQL administrator.
CREATE EXTENSION IF NOT EXISTS pg_cron;

SELECT cron.schedule(
    'monthly-payroll-processing',
    '0 2 1 * *',
    $job$CALL pr_process_payroll(
        (date_trunc('month', CURRENT_DATE) - INTERVAL '1 month')::DATE
    );$job$
);

-- Inspect the scheduled job:
SELECT jobid, jobname, schedule, command, active
FROM cron.job
WHERE jobname = 'monthly-payroll-processing';

-- Inspect its execution history:
SELECT *
FROM cron.job_run_details
WHERE jobid = (
    SELECT jobid
    FROM cron.job
    WHERE jobname = 'monthly-payroll-processing'
)
ORDER BY start_time DESC;

