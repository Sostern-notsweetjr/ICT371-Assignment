-- (c) PROCEDURE: RECEIVE A FARMER DELIVERY [8 MARKS]
CREATE OR REPLACE PROCEDURE pr_receive_delivery(
    p_farmer_id INTEGER,
    p_grade CHAR(1),
    p_weight NUMERIC,
    p_date DATE
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_farmer_id IS NULL OR p_grade IS NULL
       OR p_weight IS NULL OR p_date IS NULL THEN
        RAISE EXCEPTION
            'Farmer, grade, weight and delivery date are required.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM farmers WHERE farmer_id = p_farmer_id
    ) THEN
        RAISE EXCEPTION 'Farmer ID % does not exist.', p_farmer_id;
    END IF;

    IF p_weight <= 0 THEN
        RAISE EXCEPTION 'Delivery weight must be greater than zero.';
    END IF;

    -- Validate the grade. The trigger independently applies its rate.
    PERFORM fn_maize_rate(p_grade);

    INSERT INTO deliveries
        (farmer_id, grade, weight_kg, unit_rate, total_value,
         delivered_on, is_paid)
    VALUES
        (p_farmer_id, UPPER(BTRIM(p_grade)), p_weight, 1.00, 1.00,
         p_date, FALSE);

    RAISE NOTICE 'Delivery recorded for farmer ID %.', p_farmer_id;
END;
$$;

