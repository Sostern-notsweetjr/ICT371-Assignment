-- (g) DAILY RECEIVABLE SNAPSHOT AND SCHEDULED JOB [6 MARKS]
CREATE OR REPLACE PROCEDURE pr_refresh_receivables()
LANGUAGE plpgsql
AS $$
DECLARE
    v_total_due NUMERIC(14,2);
BEGIN
    SELECT COALESCE(SUM(charge - amount_paid), 0.00)
      INTO v_total_due
      FROM bills
     WHERE amount_paid < charge;

    INSERT INTO receivable_snapshot (snapshot_date, total_due)
    VALUES (CURRENT_DATE, v_total_due)
    ON CONFLICT (snapshot_date)
    DO UPDATE SET total_due = EXCLUDED.total_due;
END;
$$;

-- Test the procedure. Running it again replaces today's total.
CALL pr_refresh_receivables();

SELECT * FROM receivable_snapshot
WHERE snapshot_date = CURRENT_DATE;

-- Schedule every day at 00:30.
-- pg_cron must be installed and enabled by the PostgreSQL server administrator.
CREATE EXTENSION IF NOT EXISTS pg_cron;

SELECT cron.schedule(
    'daily-receivables-snapshot',
    '30 0 * * *',
    'CALL pr_refresh_receivables();'
);

-- Inspect the scheduled job:
SELECT jobid, jobname, schedule, command, active
FROM cron.job
WHERE jobname = 'daily-receivables-snapshot';

