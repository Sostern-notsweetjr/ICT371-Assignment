-- (e) VIEW: OVERDUE BILLS [5 MARKS]
CREATE OR REPLACE VIEW v_overdue_bills AS
SELECT
    c.full_name AS customer_name,
    b.due_on,
    (b.charge - b.amount_paid)::NUMERIC(12,2) AS outstanding_amount
FROM bills b
JOIN readings r ON r.reading_id = b.reading_id
JOIN customers c ON c.customer_id = r.customer_id
WHERE b.due_on < CURRENT_DATE
  AND b.amount_paid < b.charge;

SELECT * FROM v_overdue_bills
ORDER BY due_on, customer_name;

-- (f) INDEX AND EXPLAIN PLAN [5 MARKS]
-- Partial index supports date searches for bills that still have a balance.
CREATE INDEX idx_unpaid_bills_due_on
ON bills(due_on)
WHERE amount_paid < charge;

-- Matching query:
SELECT bill_id, reading_id, due_on,
       charge - amount_paid AS outstanding_amount
FROM bills
WHERE due_on < CURRENT_DATE
  AND amount_paid < charge
ORDER BY due_on;

EXPLAIN
SELECT bill_id, reading_id, due_on,
       charge - amount_paid AS outstanding_amount
FROM bills
WHERE due_on < CURRENT_DATE
  AND amount_paid < charge
ORDER BY due_on;

