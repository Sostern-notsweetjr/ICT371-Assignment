-- (g) SERVICE ALERTS AND SCHEDULED JOB [6 MARKS]
CREATE OR REPLACE PROCEDURE pr_refresh_service_alerts()
LANGUAGE plpgsql
AS $$
BEGIN
    -- Insert or refresh one alert for every vehicle currently due.
    INSERT INTO service_alerts
        (vehicle_id, km_since_service, flagged_on)
    SELECT
        vehicle_id,
        current_odometer - last_service_odometer,
        CURRENT_DATE
    FROM vehicles
    WHERE (current_odometer - last_service_odometer) >= 5000
    ON CONFLICT (vehicle_id)
    DO UPDATE SET
        km_since_service = EXCLUDED.km_since_service,
        flagged_on = EXCLUDED.flagged_on;

    -- Remove alerts for vehicles that are no longer due.
    DELETE FROM service_alerts a
    WHERE NOT EXISTS (
        SELECT 1
        FROM vehicles v
        WHERE v.vehicle_id = a.vehicle_id
          AND (v.current_odometer - v.last_service_odometer) >= 5000
    );
END;
$$;

-- Test alert refresh and display the current alerts.
CALL pr_refresh_service_alerts();

SELECT a.vehicle_id, v.registration, a.km_since_service, a.flagged_on
FROM service_alerts a
JOIN vehicles v ON v.vehicle_id = a.vehicle_id
ORDER BY a.vehicle_id;

-- Schedule every Monday at 06:00.
-- Cron fields: minute=0, hour=6, any day-of-month, any month, Monday.
-- pg_cron must be installed and enabled by the PostgreSQL server administrator.
CREATE EXTENSION IF NOT EXISTS pg_cron;

SELECT cron.schedule(
    'weekly-service-alert-refresh',
    '0 6 * * 1',
    'CALL pr_refresh_service_alerts();'
);

-- Inspect the scheduled job:
SELECT jobid, jobname, schedule, command, active
FROM cron.job
WHERE jobname = 'weekly-service-alert-refresh';

