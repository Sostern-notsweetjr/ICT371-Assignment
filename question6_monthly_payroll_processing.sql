-- (e) VIEW: PAYROLL REPORT [5 MARKS]
-- Do not filter by active: historical payroll remains visible
-- even when an employee later becomes inactive.
CREATE OR REPLACE VIEW v_payroll_report AS
SELECT
    e.employee_id,
    e.full_name,
    p.pay_month,
    p.gross_pay,
    p.net_pay
FROM employees e
JOIN payroll p
  ON p.employee_id = e.employee_id;

-- (f) INDEX AND EXPLAIN PLAN [5 MARKS]
-- The unique constraint above already creates an index on
-- (employee_id, pay_month). This separate index supports reports
-- filtered by pay_month across all employees.
CREATE INDEX idx_payroll_pay_month
    ON payroll(pay_month);

