-- (b) FUNCTION: RETURN THE RATE FOR A GRADE [6 MARKS]
CREATE OR REPLACE FUNCTION fn_maize_rate(p_grade CHAR(1))
RETURNS NUMERIC(10,2)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_grade IS NULL THEN
        RAISE EXCEPTION 'Maize grade cannot be NULL.';
    END IF;

    CASE UPPER(BTRIM(p_grade))
        WHEN 'A' THEN RETURN 5.00;
        WHEN 'B' THEN RETURN 4.00;
        WHEN 'C' THEN RETURN 3.00;
        ELSE
            RAISE EXCEPTION
                'Unsupported maize grade: %. Use A, B or C.', p_grade;
    END CASE;
END;
$$;

-- Function examples:
SELECT fn_maize_rate('A') AS grade_a_rate; -- K5.00
SELECT fn_maize_rate('B') AS grade_b_rate; -- K4.00
SELECT fn_maize_rate('C') AS grade_c_rate; -- K3.00

-- (d) TRIGGER FUNCTION: APPLY THE PRICING RULE [8 MARKS]
CREATE OR REPLACE FUNCTION trg_calculate_delivery_value()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.weight_kg IS NULL OR NEW.weight_kg <= 0 THEN
        RAISE EXCEPTION
            'Delivery weight must be greater than zero. Supplied: %.',
            NEW.weight_kg;
    END IF;

    -- Always derive the rate and total from the grade and weight.
    -- This prevents direct SQL from storing a different price.
    NEW.unit_rate := fn_maize_rate(NEW.grade);
    NEW.total_value := ROUND(NEW.weight_kg * NEW.unit_rate, 2);

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_set_delivery_value
BEFORE INSERT OR UPDATE ON deliveries
FOR EACH ROW
EXECUTE FUNCTION trg_calculate_delivery_value();

