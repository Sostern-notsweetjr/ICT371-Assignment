-- QUESTION 8: TRANSPORT FLEET MAINTENANCE
-- PostgreSQL / PLpgSQL
--
-- Rule: a vehicle is due for service when it has travelled at least
-- 5,000 kilometres since its last service.
-- Every new trip must start at the vehicle's current odometer value.
-- The scheduled job requires pg_cron to be installed and enabled.

-- =========================================================
-- CLEAN-UP: allows this script to be rerun
-- =========================================================
DROP VIEW IF EXISTS v_service_due CASCADE;
DROP TABLE IF EXISTS service_alerts CASCADE;
DROP TABLE IF EXISTS trips CASCADE;
DROP TABLE IF EXISTS vehicles CASCADE;
DROP FUNCTION IF EXISTS fn_service_due(INTEGER) CASCADE;
DROP PROCEDURE IF EXISTS pr_record_trip(INTEGER, DATE, NUMERIC, NUMERIC) CASCADE;
DROP FUNCTION IF EXISTS trg_update_vehicle_odometer() CASCADE;
DROP PROCEDURE IF EXISTS pr_refresh_service_alerts() CASCADE;

-- (a) TABLES AND SEED DATA [6 MARKS]
CREATE TABLE vehicles (
    vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration VARCHAR(20) NOT NULL UNIQUE,
    current_odometer NUMERIC(12,2) NOT NULL
        CHECK (current_odometer >= 0),
    last_service_odometer NUMERIC(12,2) NOT NULL
        CHECK (last_service_odometer >= 0),
    CHECK (last_service_odometer <= current_odometer)
);

CREATE TABLE trips (
    trip_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles(vehicle_id),
    trip_on DATE NOT NULL,
    start_odometer NUMERIC(12,2) NOT NULL
        CHECK (start_odometer >= 0),
    end_odometer NUMERIC(12,2) NOT NULL
        CHECK (end_odometer > start_odometer)
);

CREATE TABLE service_alerts (
    vehicle_id INTEGER PRIMARY KEY REFERENCES vehicles(vehicle_id),
    km_since_service NUMERIC(12,2) NOT NULL
        CHECK (km_since_service >= 0),
    flagged_on DATE NOT NULL
);

