-- (d) TRIGGER FUNCTION: AUDIT ACTUAL STATUS CHANGES [8 MARKS]
CREATE OR REPLACE FUNCTION trg_audit_application_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- Do not create an audit row if the status did not change.
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO decision_audit
            (application_id, old_status, new_status, changed_at)
        VALUES
            (NEW.application_id, OLD.status, NEW.status, CURRENT_TIMESTAMP);
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_application_status_audit
AFTER UPDATE OF status ON applications
FOR EACH ROW
EXECUTE FUNCTION trg_audit_application_status();

-- (c) PROCEDURE: ASSESS ONE PENDING APPLICATION [8 MARKS]
CREATE OR REPLACE PROCEDURE pr_assess_application(p_application_id INTEGER)
LANGUAGE plpgsql
AS $$
DECLARE
    v_age INTEGER;
    v_income NUMERIC(12,2);
    v_mark NUMERIC(5,2);
    v_status VARCHAR(10);
    v_eligible BOOLEAN;
BEGIN
    SELECT age_at_application, monthly_income, average_mark, status
      INTO v_age, v_income, v_mark, v_status
      FROM applications
     WHERE application_id = p_application_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Application ID % does not exist.', p_application_id;
    END IF;

    IF v_status <> 'PENDING' THEN
        RAISE EXCEPTION
            'Application ID % has already been assessed (status: %).',
            p_application_id, v_status;
    END IF;

    v_eligible := fn_scholarship_eligible(v_age, v_income, v_mark);

    UPDATE applications
       SET status = CASE
           WHEN v_eligible THEN 'APPROVED'
           ELSE 'REJECTED'
       END
     WHERE application_id = p_application_id;

    RAISE NOTICE 'Application % assessed: %.',
        p_application_id,
        CASE WHEN v_eligible THEN 'APPROVED' ELSE 'REJECTED' END;
END;
$$;

