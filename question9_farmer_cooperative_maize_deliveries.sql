-- (e) VIEW: TOTAL UNPAID VALUE PER FARMER [5 MARKS]
-- LEFT JOIN includes farmers with no unpaid deliveries.
CREATE OR REPLACE VIEW v_farmer_amount_due AS
SELECT
    f.farmer_number,
    f.full_name,
    COALESCE(SUM(d.total_value)
        FILTER (WHERE d.is_paid = FALSE), 0.00)::NUMERIC(14,2)
        AS total_unpaid_value
FROM farmers f
LEFT JOIN deliveries d
    ON d.farmer_id = f.farmer_id
GROUP BY f.farmer_id, f.farmer_number, f.full_name;

SELECT * FROM v_farmer_amount_due
ORDER BY farmer_number;

