-- (b) FUNCTION
CREATE OR REPLACE FUNCTION fn_daily_load(p_doctor_id INTEGER, p_day DATE)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_count INTEGER;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM doctors WHERE doctor_id = p_doctor_id) THEN
        RAISE EXCEPTION 'Unknown doctor ID %', p_doctor_id;
    END IF;
    SELECT COUNT(*) INTO v_count
    FROM appointments
    WHERE doctor_id = p_doctor_id
      AND appointment_day = p_day
      AND status <> 'CANCELLED';
    RETURN COALESCE(v_count, 0);
END;
$$;

-- (e) VIEW: today's BOOKED appointments only
CREATE OR REPLACE VIEW v_today_appointments AS
SELECT a.appointment_id, p.full_name AS patient_name,
       d.full_name AS doctor_name, a.slot_time
FROM appointments a
JOIN patients p ON p.patient_id = a.patient_id
JOIN doctors d ON d.doctor_id = a.doctor_id
WHERE a.appointment_day = CURRENT_DATE
  AND a.status = 'BOOKED';

-- (f) INDEX and matching EXPLAIN
CREATE INDEX idx_appointments_day_doctor
ON appointments(appointment_day, doctor_id);
EXPLAIN
SELECT appointment_id, slot_time, status
FROM appointments
WHERE appointment_day = CURRENT_DATE AND doctor_id = 1;

-- (g) DAILY SUMMARY PROCEDURE
CREATE OR REPLACE PROCEDURE pr_refresh_clinic_summary(p_day DATE)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_day IS NULL THEN RAISE EXCEPTION 'Summary date cannot be NULL'; END IF;
    INSERT INTO clinic_summary(summary_date, booked_count, attended_count, cancelled_count)
    SELECT p_day,
       COUNT(*) FILTER (WHERE status = 'BOOKED'),
       COUNT(*) FILTER (WHERE status = 'ATTENDED'),
       COUNT(*) FILTER (WHERE status = 'CANCELLED')
    FROM appointments WHERE appointment_day = p_day
    ON CONFLICT(summary_date) DO UPDATE SET
       booked_count = EXCLUDED.booked_count,
       attended_count = EXCLUDED.attended_count,
       cancelled_count = EXCLUDED.cancelled_count;
END;
$$;
CALL pr_refresh_clinic_summary(CURRENT_DATE);

